#!/usr/bin/env python3
"""Writes docs/i18n/review-zh.md: every user-visible string, English → zh-Hans → zh-Hant, grouped by screen,
for the user's Chinese review (i18n-01 I5). Sources: the ARB files and tool/i18n/native.json.

Usage: python3 tool/i18n_review_zh.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARB = ROOT / 'mobile/lib/l10n'
OUT = ROOT / 'docs/i18n/review-zh.md'

# Key prefix → screen, in reading order (first match wins).
GROUPS = [
    ('common', 'Shared buttons'),
    ('tab', 'Tabs and panes'),
    ('pane', 'Tabs and panes'),
    ('record', 'Record'),
    ('profileReason', 'Record'),
    ('draft', 'Drafts'),
    ('settings', 'Settings'),
    ('keyboard', 'Settings › Keyboard setup'),
    ('useInApps', 'Settings › Use in apps'),
    ('fieldRules', 'Settings › Field rules'),
    ('fieldKind', 'Settings › Field rules'),
    ('profile', 'Profile editor and built-in profiles'),
    ('shell', 'Messages (snack bars)'),
    ('failure', 'Error messages'),
    ('nearby', 'Desktop (Nearby microphone)'),
    ('pro', 'Shinsoku Pro (purchase, locks)'),
]
NATIVE_GROUPS = {
    'mobile/ios/ShinsokuKeyboard/Localizable.xcstrings': 'Keyboard (keys, status, VoiceOver)',
    'mobile/ios/Runner/Localizable.xcstrings': 'Shortcuts actions (App Intents)',
    'AppShortcuts.strings': 'Siri / Spotlight phrases and ready-made Shortcuts tiles',
    'mobile/ios/Runner/InfoPlist.xcstrings': 'System permission prompts',
}


def cell(text):
    return str(text).replace('|', '\\|').replace('\n', ' ')


def load(name):
    return {k: v for k, v in json.loads((ARB / name).read_text()).items() if not k.startswith('@')}


def main():
    en, hans, hant = load('app_en.arb'), load('app_zh_Hans.arb'), load('app_zh_Hant.arb')
    sections = {}
    for key, value in en.items():
        group = next(title for prefix, title in GROUPS if key.startswith(prefix))
        sections.setdefault(group, []).append((value, hans[key], hant[key]))
    native = json.loads((ROOT / 'tool/i18n/native.json').read_text())
    i_hans, i_hant = native['languages'].index('zh-Hans'), native['languages'].index('zh-Hant')
    info = json.loads((ROOT / 'mobile/ios/Runner/InfoPlist.xcstrings').read_text())['strings']
    english_info = {k: v['localizations']['en']['stringUnit']['value'] for k, v in info.items()}
    for rel, title in NATIVE_GROUPS.items():
        for key, values in native[rel].items():
            sections.setdefault(title, []).append((english_info.get(key, key), values[i_hans], values[i_hant]))

    lines = [
        '# Chinese review — every user-visible string',
        '',
        'Generated by `tool/i18n_review_zh.py` from the ARB files and `tool/i18n/native.json`; do not edit by '
        'hand. Terms: `docs/i18n/glossary.md`.',
        '',
        'How to review: mark a row (or write the better wording next to it) and send it back; the fix goes into the '
        'ARB / native.json and this file is regenerated. zh-Hans is for Singapore, Malaysia and overseas readers '
        '(mainland-neutral); zh-Hant uses Taiwan wording (Hong Kong falls back to it). The translation-profile '
        'prompts (`… -> EN`) are sent to the AI model and stay in English on purpose.',
        '',
    ]
    for title, rows in sections.items():
        lines += [f'## {title}', '', '| English | 简体中文 (zh-Hans) | 繁體中文 (zh-Hant) |', '|---|---|---|']
        lines += [f'| {cell(a)} | {cell(b)} | {cell(c)} |' for a, b, c in rows]
        lines.append('')
    OUT.write_text('\n'.join(lines))
    print(f'wrote {OUT.relative_to(ROOT)} ({sum(len(r) for r in sections.values())} strings)')


if __name__ == '__main__':
    main()
