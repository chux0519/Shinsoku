#!/usr/bin/env python3
"""Regenerates mobile/lib/app/debug_live_fixtures.dart from T1's streaming fixtures
(mobile/test/fixtures/streaming/*.json). Used only by the DEBUG launch argument
-ShinsokuSceneLiveFixture; mobile/test/app/live_fixture_test.dart fails when the two drift."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent / 'mobile'
src = sorted((root / 'test/fixtures/streaming').glob('*.json'))
out = ["// GENERATED by tool/gen_live_fixtures.py from test/fixtures/streaming/*.json. Do not edit.",
       "// DEBUG only (-ShinsokuSceneLiveFixture <name>): referenced behind kDebugMode, so release",
       "// builds drop it. Fixture content is `example` data, no keys.",
       "const debugLiveFixtures = <String, String>{"]
for p in src:
    compact = json.dumps(json.load(open(p, encoding='utf-8')), ensure_ascii=False, separators=(',', ':'))
    assert "'''" not in compact
    out.append(f"  '{p.stem}': r'''{compact}''',")
out.append("};\n")
(root / 'lib/app/debug_live_fixtures.dart').write_text('\n'.join(out), encoding='utf-8')
print(f"{len(src)} fixtures")
