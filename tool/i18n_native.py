#!/usr/bin/env python3
"""Write the native translations (i18n-01 I5) from tool/i18n/native.json.

- String Catalogs: every listed key gets `localizations.<lang>` = translated value (state `translated`).
  Entries marked `shouldTranslate: false` are left alone. Output keeps Xcode's format (sorted keys, " : ").
- App Shortcut phrases: `mobile/ios/Runner/<lang>.lproj/AppShortcuts.strings`, comments copied from the
  English file. Registering a new file in the Xcode variant group is a separate step (see I5-implementation.md).

Usage: python3 tool/i18n_native.py [--check]   (--check: exit 1 if a file would change)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'tool/i18n/native.json'
EN_SHORTCUTS = ROOT / 'mobile/ios/Runner/en.lproj/AppShortcuts.strings'


def catalog_text(path, rows, languages):
    doc = json.loads(path.read_text())
    for key, values in rows.items():
        entry = doc['strings'].get(key)
        if entry is None:
            raise SystemExit(f'{path.relative_to(ROOT)}: "{key}" is not in the catalog')
        if entry.get('shouldTranslate') is False:
            continue
        locs = entry.setdefault('localizations', {})
        for lang, value in zip(languages, values, strict=True):
            locs[lang] = {'stringUnit': {'state': 'translated', 'value': value}}
    return json.dumps(doc, indent=2, ensure_ascii=False, separators=(',', ' : '), sort_keys=True) + '\n'


def shortcuts_text(rows, index, lang):
    english = EN_SHORTCUTS.read_text()
    out = [f'/* App Shortcut phrases, {lang}. Generated by tool/i18n_native.py from tool/i18n/native.json;\n'
           '   edit that file, not this one. Every phrase keeps ${applicationName} (and ${profile}). */', '']
    for m in re.finditer(r'(/\*(?:(?!\*/).)*\*/)\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;', english, re.S):
        comment, key = m.group(1), m.group(2)
        if key not in rows:
            raise SystemExit(f'AppShortcuts.strings: "{key}" has no translation in {DATA.relative_to(ROOT)}')
        value = rows[key][index].replace('"', '\\"')
        out += [comment, f'"{key}" = "{value}";', '']
    return '\n'.join(out)


def main():
    check = '--check' in sys.argv
    data = json.loads(DATA.read_text())
    languages = data['languages']
    outputs = {}
    for rel, rows in data.items():
        if rel.endswith('.xcstrings'):
            outputs[ROOT / rel] = catalog_text(ROOT / rel, rows, languages)
    for i, lang in enumerate(languages):
        outputs[ROOT / f'mobile/ios/Runner/{lang}.lproj/AppShortcuts.strings'] = shortcuts_text(
            data['AppShortcuts.strings'], i, lang)
    changed = [p for p, text in outputs.items() if not p.is_file() or p.read_text() != text]
    if check:
        for p in changed:
            print(f'{p.relative_to(ROOT)}: out of date (run tool/i18n_native.py)')
        return 1 if changed else 0
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outputs[p])
        print(f'wrote {p.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
